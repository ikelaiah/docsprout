"""Safe filesystem primitives for generated documentation output."""

from collections.abc import Iterator
from contextlib import contextmanager
from pathlib import Path
import shutil
import tempfile

from .errors import DocSproutError

OWNERSHIP_MARKER = ".docsprout-site"
LEGACY_OWNERSHIP_MARKER = ".dockit-fp-site"


def _owned_marker(output: Path) -> str | None:
    for marker in (OWNERSHIP_MARKER, LEGACY_OWNERSHIP_MARKER):
        if (output / marker).is_file():
            return marker
    return None


def _validate_output(output: Path) -> None:
    if output.exists():
        if not output.is_dir():
            raise DocSproutError(f"Output path is not a directory: {output}")
        if _owned_marker(output) is None:
            raise DocSproutError(
                f"Refusing to replace output directory {output}: it is not owned by DocSprout "
                f"(missing {OWNERSHIP_MARKER})."
            )


def prepare_output(output: Path) -> None:
    """Empty a DocSprout-owned output directory and recreate its marker.

    Output generated by the pre-rebrand DocKit-FP name is recognised through
    its legacy marker, then replaced with the canonical DocSprout marker.
    """
    output = output.resolve()
    _validate_output(output)
    if output.exists():
        shutil.rmtree(output)
    output.mkdir(parents=True)
    (output / OWNERSHIP_MARKER).write_text("DocSprout generated output.\n", encoding="utf-8")


@contextmanager
def staged_output(output: Path) -> Iterator[Path]:
    """Publish a completed build, restoring the old site if installation fails.

    Stage beside the destination so directory renames stay on one filesystem.
    No generated files become visible until the caller finishes successfully.
    """
    output = output.resolve()
    _validate_output(output)
    output.parent.mkdir(parents=True, exist_ok=True)
    workspace = Path(tempfile.mkdtemp(prefix=f".{output.name}-", dir=output.parent))
    staged, previous = workspace / "site", workspace / "previous"
    published = False
    try:
        yield staged
        _validate_output(output)
        if output.exists():
            output.rename(previous)
        try:
            staged.rename(output)
        except OSError:
            if previous.exists():
                previous.rename(output)
            raise
        published = True
    finally:
        # If restoration itself fails (for example, a Windows file lock), keep
        # the previous site for recovery rather than deleting the only copy.
        if published or not previous.exists():
            shutil.rmtree(workspace)
